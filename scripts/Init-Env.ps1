[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$projectDirectory = Split-Path -Parent $PSScriptRoot
$environmentPath = Join-Path $projectDirectory '.env'
if (Test-Path -LiteralPath $environmentPath) {
    Write-Host '.env already exists; no values were changed.'
    exit 0
}

function New-SecureSecret {
    param([int] $ByteCount = 32)
    $bytes = New-Object byte[] $ByteCount
    $generator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $generator.GetBytes($bytes) } finally { $generator.Dispose() }
    return ([BitConverter]::ToString($bytes)).Replace('-', '').ToLowerInvariant()
}

$databasePassword = New-SecureSecret
$jwtSecret = New-SecureSecret -ByteCount 48
$adminPassword = New-SecureSecret -ByteCount 24
$contents = @"
# Local credentials generated by Init-Env.ps1. Do not commit or share this file.
POSTGRES_DB=ktor_realtime
POSTGRES_USER=realtime_app
POSTGRES_PASSWORD=$databasePassword
JWT_SECRET=$jwtSecret
ADMIN_USERNAME=admin
ADMIN_PASSWORD=$adminPassword
APP_PORT=8091
PG_PORT=55435
"@

# CreateNew also protects against an accidental overwrite by concurrent launches.
$stream = [System.IO.File]::Open($environmentPath, [System.IO.FileMode]::CreateNew,
    [System.IO.FileAccess]::Write, [System.IO.FileShare]::None)
try {
    $bytes = (New-Object System.Text.UTF8Encoding($false)).GetBytes($contents + "`n")
    $stream.Write($bytes, 0, $bytes.Length)
} finally { $stream.Dispose() }
Write-Host 'Created .env with random secrets. The initial admin password is in ADMIN_PASSWORD.'
